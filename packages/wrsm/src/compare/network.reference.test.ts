import { execFileSync } from 'node:child_process';
import { mkdirSync, readdirSync, readFileSync, realpathSync, statSync, writeFileSync } from 'node:fs';
import { dirname, isAbsolute, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { makeSamiAquiferStep, samiAquiferInit, samiAquiferStep } from '../groundwater/sami/aquifer.js';
import type { SamiOptionsInput, SamiRunParts } from '../groundwater/sami/index.js';
import type { PitmanOptions } from '../runoff/pitman.js';
import { samiInterflow, samiInterflowRouter, samiSoilPass } from '../groundwater/sami/soil.js';
import { readBundle } from '../io/bundle.js';
import { runNetwork } from '../network/run-network.js';
import { DEFAULT_SIMULATORS } from '../run.js';
import { compareNetworkWithReference, type RouteComparison } from './network.js';

// Local-only whole-network comparison (issue #3 rules 2 and 3; Round 6.5):
// every .NET under WRSM_REFERENCE_DIR run in historical mode with the real
// Sami parts, every route with a <code>RQ<n>.ANS compared, ranked by error,
// origins of divergence marked. Skips only when the variable is unset.
//
// Console output is counts and percentages only (networks by index). The
// detailed ranking, with folder names, goes to
// ../pitman-private/reports/sami-comparison.md, outside the repo.
// WRSM_SAMI_VARIANTS=all also runs every
// OQ-S2/OQ-S3 reading (sami.md §8) so the winner can be picked.

const dir = process.env.WRSM_REFERENCE_DIR;
const allVariants = process.env.WRSM_SAMI_VARIANTS === 'all';

/** The real parts (soil.ts, aquifer.ts); `makeAquiferStep` carries the aquifer switches. */
const PARTS: SamiRunParts = { soilPass: samiSoilPass, interflow: samiInterflow, interflowRouter: samiInterflowRouter, aquiferInit: samiAquiferInit, aquiferStep: samiAquiferStep, makeAquiferStep: makeSamiAquiferStep };

/** A Sami reading plus Pitman core options (R2-1; OQ-22 decides whether the TL lag can go negative). */
interface Variant {
	readonly sami?: SamiOptionsInput;
	readonly pitman?: Partial<PitmanOptions>;
}
const perStep = { routing: 'perStep' } as const;
const readingA = { finalRunoff: 'surfacePlusSami' } as const;
const VARIANTS: Record<string, Variant> = allVariants
	? {
			default: {},
			'R6-R6 baseline: per-step Muskingum + OQ-S3 (a)': { pitman: perStep, sami: readingA },
			'OQ-22 per-step Muskingum (R6-R6), OQ-S3 (c)': { pitman: perStep },
			'OQ-S3 (a) surface + Sami interflow + baseflow, shift routing': { sami: readingA },
			'OQ-S3 (b) total + baseflow': { sami: { finalRunoff: 'totalPlusBaseflow' } },
			'OQ-S3 HEAD (ii) surface': { sami: { headRunoff: 'surface' } },
			'OQ-S3 unlagged parts': { sami: { pitmanParts: 'unlagged' } },
			'OQ-S2 (b) recharge drains S': { sami: { soilFeedback: 'rechargeDrainsS' } },
			'OQ-S4 step-mean S': { sami: { soilMoisture: 'stepMean' } },
			'R6-R3 clamp negative': { sami: { negativeRunoff: 'clamp' } }
		}
	: { default: {} };

function walk(root: string): string[] {
	return readdirSync(root).flatMap((name) => {
		const path = join(root, name);
		return statSync(path).isDirectory() ? walk(path) : [path];
	});
}

const repoRoot = fileURLToPath(new URL('../../../../', import.meta.url));
const fmt = (v: number | null | undefined, d = 2) => (v === null || v === undefined ? 'n/a' : v.toFixed(d));
const median = (xs: number[]) => {
	if (xs.length === 0) return null;
	const s = [...xs].sort((a, b) => a - b);
	return s.length % 2 ? s[(s.length - 1) / 2]! : (s[s.length / 2 - 1]! + s[s.length / 2]!) / 2;
};
/** An error message with quoted names and file names masked (they may name the network). */
const mask = (text: string) => {
	let out = text.replace(/'[^']*'/g, "'…'").replace(/\b[\w-]+\.(DAT|RAN|NET|ANS|ABS)\b/gi, '<file>');
	for (let prev = ''; prev !== out; ) (prev = out), (out = out.replace(/\([^()]*\)/g, '…'));
	return out.replace(/-?\d+\.\d+/g, '<x>').replace(/\b(in|month) [A-Z][a-z]{2} \d{4}|month \d+/g, 'in <month>');
};

describe.skipIf(!dir)('whole-network comparison against WRSM_REFERENCE_DIR (Sami)', () => {
	it('runs every reference network and ranks every route by error', () => {
		const files = walk(dir as string);
		// A folder reachable twice (a symlink) is one network: count it once.
		const nets = [...new Map(files.filter((p) => /\.NET$/i.test(p)).map((p) => [realpathSync(p), p])).values()];
		const report: string[] = ['# Sami whole-network comparison', '', `Generated by \`src/compare/network.reference.test.ts\`; local only (git-ignored).`, ''];
		let total = 0;
		const summary: string[] = ['## Summary', ''];

		for (const [variant, options] of Object.entries(VARIANTS)) {
			const tally = { networks: 0, ran: 0, failed: 0, routes: 0, passing: 0, origins: 0, errors: {} as Record<string, number>, byType: {} as Record<string, { routes: number; passing: number; origins: number }> };
			const absMar: number[] = [];
			const ruMar: number[] = [];
			const ruNse: number[] = [];
			const worst: { net: string; row: RouteComparison }[] = [];
			report.push(`## ${variant}`, '');
			nets.forEach((netPath, n) => {
				tally.networks++;
				const folder = dirname(netPath);
				const input = Object.fromEntries(walk(folder).map((p) => [relative(folder, p).split('\\').join('/'), readFileSync(p, 'latin1')]));
				const net = relative(folder, netPath).split('\\').join('/');
				const label = relative(dir as string, netPath);
				const read = readBundle(input, { network: net });
				if (!read.ok) {
					tally.failed++;
					tally.errors['unreadable bundle'] = (tally.errors['unreadable bundle'] ?? 0) + 1;
					report.push(`- ${label}: bundle unreadable`);
					return;
				}
				const c = compareNetworkWithReference(read.bundle, (b) =>
					runNetwork(b, { kind: 'historical' }, { simulators: DEFAULT_SIMULATORS, samiParts: PARTS, ...options })
				);
				if (!c.ok) {
					tally.failed++;
					const text = mask(c.error instanceof Error ? c.error.message : String(c.error)).replace(/^RU \d+: /, 'RU n: ').slice(0, 120);
					tally.errors[text] = (tally.errors[text] ?? 0) + 1;
					report.push(`- ${label}: run failed (${c.references} references): ${c.error instanceof Error ? c.error.message : String(c.error)}`);
					return;
				}
				tally.ran++;
				tally.routes += c.routes.length;
				tally.passing += c.routes.filter((r) => !r.fails).length;
				tally.origins += c.routes.filter((r) => r.origin).length;
				for (const r of c.routes) {
					const type = r.module?.type ?? 'zero source';
					const t = (tally.byType[type] ??= { routes: 0, passing: 0, origins: 0 });
					t.routes++;
					if (!r.fails) t.passing++;
					if (type === 'RU' && r.comparison?.marPctDiff != null) ruMar.push(r.comparison.marPctDiff);
					if (type === 'RU' && r.comparison?.nse != null) ruNse.push(r.comparison.nse);
					if (r.origin) t.origins++;
					if (r.comparison?.marPctDiff != null) absMar.push(Math.abs(r.comparison.marPctDiff));
					worst.push({ net: label, row: r });
				}
				report.push(`- ${label} (network #${n + 1}): ${c.routes.length} routes, ${c.routes.filter((r) => !r.fails).length} within thresholds, origins: ${c.routes.filter((r) => r.origin).map((r) => `RQ${r.route} (${r.module ? `${r.module.type} ${r.module.number}` : 'zero source'}, MAR ${fmt(r.comparison?.marPctDiff)} %, NSE ${fmt(r.comparison?.nse, 3)}, first ${r.comparison?.firstDivergingMonth ? `${r.comparison.firstDivergingMonth.year}/${r.comparison.firstDivergingMonth.month}` : '-'})`).join('; ') || 'none'}`);
			});
			const order = (r: RouteComparison) => (r.comparison?.marPctDiff == null ? Infinity : Math.abs(r.comparison.marPctDiff));
			worst.sort((a, b) => order(b.row) - order(a.row));
			report.push('', '| network | route | module | origin | MAR sim | MAR ref | % diff | NSE | first diverging |', '|---|---|---|---|---|---|---|---|---|');
			for (const { net, row } of worst.slice(0, 60)) {
				const c = row.comparison;
				report.push(`| ${net} | RQ${row.route} | ${row.module ? `${row.module.type} ${row.module.number}` : '0'} | ${row.origin ? 'yes' : ''} | ${fmt(c?.marSimulated, 3)} | ${fmt(c?.marReference, 3)} | ${fmt(c?.marPctDiff)} | ${fmt(c?.nse, 3)} | ${c?.firstDivergingMonth ? `${c.firstDivergingMonth.year}/${c.firstDivergingMonth.month}` : row.problem ?? '-'} |`);
			}
			report.push('');
			console.log(
				`sami comparison [${variant}]: ${tally.ran}/${tally.networks} networks ran (${tally.failed} failed); ` +
					`${tally.passing}/${tally.routes} routes within |MAR| ≤ 1 % and NSE ≥ 0.99; ${tally.origins} origins; ` +
					`median |MAR diff| ${fmt(median(absMar))} %`
			);
			for (const [text, count] of Object.entries(tally.errors)) console.log(`  ${count} × ${text}`);
			console.log(`  by controlling module: ${Object.entries(tally.byType).map(([k, v]) => `${k} ${v.passing}/${v.routes} pass, ${v.origins} origins`).join('; ')}`);
			summary.push(`- **${variant}**: ${tally.ran}/${tally.networks} networks ran; ${tally.passing}/${tally.routes} routes within thresholds; ${tally.origins} origins; median |MAR diff| ${fmt(median(absMar))} %`);
			const ruLine = `RU routes: median MAR diff ${fmt(median(ruMar))} % (signed; ${ruMar.filter((v) => v > 0).length} high, ${ruMar.filter((v) => v < 0).length} low), median NSE ${fmt(median(ruNse), 3)}`;
			summary.push(`  - ${ruLine}`);
			console.log(`  ${ruLine}`);
			summary.push(`  - by controlling module: ${Object.entries(tally.byType).map(([k, v]) => `${k} ${v.passing}/${v.routes} pass, ${v.origins} origins`).join('; ')}`);
			for (const [text, count] of Object.entries(tally.errors)) summary.push(`  - ${count} × ${text}`);
			total += tally.networks;
		}

		// The report names reference folders and carries per-module figures, so it
		// goes to the private folder beside the main checkout (../pitman-private,
		// or WRSM_PRIVATE_DIR), never into the repo (CLAUDE.md project rule 2).
		const gitDir = execFileSync('git', ['rev-parse', '--path-format=absolute', '--git-common-dir'], { cwd: repoRoot, encoding: 'utf8' }).trim();
		const mainCheckout = dirname(gitDir);
		const reportDir = join(resolve(process.env.WRSM_PRIVATE_DIR ?? join(mainCheckout, '..', 'pitman-private')), 'reports');
		for (const root of [repoRoot, mainCheckout]) {
			const rel = relative(root, reportDir);
			if (!rel.startsWith('..') && !isAbsolute(rel)) throw new Error(`refusing to write a reference report inside the repo: ${reportDir}`);
		}
		mkdirSync(reportDir, { recursive: true });
		writeFileSync(join(reportDir, 'sami-comparison.md'), [...report.slice(0, 4), ...summary, '', ...report.slice(4)].join('\n'));
		expect(total).toBeGreaterThan(0);
	}, 600_000);
});
